#!/usr/bin/env node
// Writes the README's tool table from what the live server says.
//
//   node scripts/sync-tools.mjs           ask the server and rewrite the table in README.md
//   node scripts/sync-tools.mjs --check   ask the server and compare; exit 1 if README.md differs
//
// The server is the only source. Its tools/list gives each tool's name, title, description
// and whether it only reads. The public API spec gives the key scope each tool needs: a
// tool's title is its operation's summary. Nothing in the table is written by hand, so
// when the API changes, rerun this and commit; the daily check in
// .github/workflows/tools.yml fails until someone does.
//
// MCP_URL and SPEC_URL point it somewhere other than production.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const MCP_URL = process.env.MCP_URL || "https://app.contactz.app/api/v1/mcp";
const SPEC_URL = process.env.SPEC_URL || "https://app.contactz.app/api/v1/openapi.json";
const CHECK = process.argv.includes("--check");
const README = path.join(path.dirname(path.dirname(fileURLToPath(import.meta.url))), "README.md");
const START = "<!-- tools:start -->";
const END = "<!-- tools:end -->";

const fail = (message) => {
  console.error(`sync-tools: ${message}`);
  process.exit(1);
};

async function fetchJSON(url, init) {
  for (let attempt = 1; ; attempt++) {
    try {
      const res = await fetch(url, { ...init, signal: AbortSignal.timeout(20000) });
      if (!res.ok) throw new Error(`${url} answered ${res.status}`);
      return await res.json();
    } catch (err) {
      if (attempt >= 4) fail(err.message);
      await new Promise((r) => setTimeout(r, 2000 * attempt));
    }
  }
}

const listed = await fetchJSON(MCP_URL, {
  method: "POST",
  headers: { "content-type": "application/json", accept: "application/json, text/event-stream" },
  body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "tools/list" }),
});
const tools = listed?.result?.tools;
if (!Array.isArray(tools) || tools.length === 0) fail(`${MCP_URL} listed no tools`);

const spec = await fetchJSON(SPEC_URL, { headers: { accept: "application/json" } });
const scopesBySummary = new Map();
for (const item of Object.values(spec.paths || {})) {
  for (const op of Object.values(item)) {
    if (op && typeof op === "object" && op.summary) {
      scopesBySummary.set(op.summary, (op.security || []).flatMap((s) => Object.values(s).flat()));
    }
  }
}

const cell = (text) => String(text).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
// The first sentence of the description's first paragraph: the rest is for the assistant.
const firstSentence = (description) => String(description || "").split(/\n\s*\n/)[0].split(/(?<=\.)\s/)[0];

const rows = tools.map((tool) => {
  if (!scopesBySummary.has(tool.title)) fail(`no operation in ${SPEC_URL} has the summary "${tool.title}" (tool ${tool.name})`);
  const scopes = scopesBySummary.get(tool.title);
  const scope = scopes.length ? scopes.map((s) => `\`${s}\``).join(", ") : "Any key";
  const readOnly = tool.annotations?.readOnlyHint ? "Yes" : "No";
  return `| \`${tool.name}\` | ${cell(tool.title)} | ${cell(firstSentence(tool.description))} | ${scope} | ${readOnly} |`;
});

const table = [
  START,
  `${tools.length} tools, as the server lists them. Generated by \`scripts/sync-tools.mjs\`.`,
  "",
  "| Tool | Title | What it does | Key scope | Read-only |",
  "|---|---|---|---|---|",
  ...rows,
  END,
].join("\n");

const current = readFileSync(README, "utf8");
const from = current.indexOf(START);
const to = current.indexOf(END);
if (from < 0 || to < from) fail(`README.md has no ${START} ... ${END} block`);
const next = current.slice(0, from) + table + current.slice(to + END.length);

if (CHECK) {
  if (next !== current) fail(`README.md's tool table differs from ${MCP_URL}. Run node scripts/sync-tools.mjs and commit.`);
  console.log(`sync-tools: README.md matches ${MCP_URL} (${tools.length} tools)`);
} else if (next === current) {
  console.log("sync-tools: already up to date");
} else {
  writeFileSync(README, next);
  console.log(`sync-tools: wrote ${tools.length} tools from ${MCP_URL}`);
}
